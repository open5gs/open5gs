#define ROT31(a, k) ((((a) << (k)) | ((a) >> (31 - (k)))) & 0x7fffffffu)
#define ROT32(a, k) (((a) << (k)) | ((a) >> (32 - (k))))

/* The LFSR represents zero as 0x7fffffff. */
static uint32_t zuc_add31(uint32_t a, uint32_t b)
{
    uint32_t sum = a + b;

    return (sum & 0x7fffffffu) + (sum >> 31);
}

static void zuc_lfsr_shift(uint32_t lfsr[16], uint32_t input)
{
    uint32_t v = lfsr[0];

    v = zuc_add31(v, ROT31(lfsr[0], 8));
    v = zuc_add31(v, ROT31(lfsr[4], 20));
    v = zuc_add31(v, ROT31(lfsr[10], 21));
    v = zuc_add31(v, ROT31(lfsr[13], 17));
    v = zuc_add31(v, ROT31(lfsr[15], 15));
    v = zuc_add31(v, input);

    memmove(lfsr, lfsr + 1, 15 * sizeof(*lfsr));
    lfsr[15] = v;
}

static uint32_t zuc_substitute(uint32_t value)
{
    return ((uint32_t)S0[value >> 24] << 24) |
           ((uint32_t)S1[(value >> 16) & 0xff] << 16) |
           ((uint32_t)S0[(value >> 8) & 0xff] << 8) |
           (uint32_t)S1[value & 0xff];
}

static uint32_t zuc_f(zuc_state_t *state)
{
    const uint32_t *lfsr = state->lfsr;
    uint32_t x0 = ((lfsr[15] & 0x7fff8000u) << 1) | (lfsr[14] & 0xffff);
    uint32_t x1 = ((lfsr[11] & 0xffff) << 16) | (lfsr[9] >> 15);
    uint32_t x2 = ((lfsr[7] & 0xffff) << 16) | (lfsr[5] >> 15);
    uint32_t w = (x0 ^ state->r1) + state->r2;
    uint32_t w1 = state->r1 + x1;
    uint32_t w2 = state->r2 ^ x2;
    uint32_t u = (w1 << 16) | (w2 >> 16);
    uint32_t v = (w2 << 16) | (w1 >> 16);

    state->r1 = zuc_substitute(
            u ^ ROT32(u, 2) ^ ROT32(u, 10) ^ ROT32(u, 18) ^ ROT32(u, 24));
    state->r2 = zuc_substitute(
            v ^ ROT32(v, 8) ^ ROT32(v, 14) ^ ROT32(v, 22) ^ ROT32(v, 30));

    return w;
}

static void zuc_init(zuc_state_t *state, const uint8_t *key, const uint8_t *iv)
{
    unsigned int i;

    for (i = 0; i < OGS_ARRAY_SIZE(state->lfsr); i++)
        state->lfsr[i] = ((uint32_t)key[i] << 23) | (KD[i] << 8) | iv[i];

    state->r1 = 0;
    state->r2 = 0;
    for (i = 0; i < 32; i++) {
        uint32_t w = zuc_f(state);

        zuc_lfsr_shift(state->lfsr, w >> 1);
    }

    /* Discard the first output of F before generating the keystream. */
    zuc_f(state);
    zuc_lfsr_shift(state->lfsr, 0);
}

static uint32_t zuc_generate_keyword(zuc_state_t *state)
{
    uint32_t x3 = ((state->lfsr[2] & 0xffff) << 16) |
        (state->lfsr[0] >> 15);
    uint32_t word = zuc_f(state) ^ x3;

    zuc_lfsr_shift(state->lfsr, 0);
    return word;
}

static void zuc_encrypt(zuc_state_t *state,
        uint8_t *input, size_t bytes, uint8_t *output)
{
    while (bytes >= 4) {
        uint32_t word = zuc_generate_keyword(state) ^
            (uint32_t)ogs_buffer_to_uint64(input, 4);

        ogs_uint64_to_buffer(word, 4, output);
        input += 4;
        output += 4;
        bytes -= 4;
    }

    if (bytes) {
        uint32_t word = zuc_generate_keyword(state);
        size_t i;

        for (i = 0; i < bytes; i++)
            output[i] = input[i] ^ (uint8_t)(word >> (24 - i * 8));
    }
}

/* The GmSSL MAC calculation uses a sliding 32-bit keystream window. */
static uint32_t zuc_mac(zuc_state_t *state, uint8_t *input, uint32_t length)
{
    uint32_t tag = 0;
    uint32_t k0 = zuc_generate_keyword(state);

    while (length) {
        uint32_t bits = ogs_min(length, 32u);
        int bytes = (bits + 7) / 8;
        uint32_t word = (uint32_t)ogs_buffer_to_uint64(input, bytes);
        uint32_t k1 = zuc_generate_keyword(state);
        uint32_t i;

        word <<= (4 - bytes) * 8;
        for (i = 0; i < bits; i++) {
            tag ^= k0 & (0u - (word >> 31));
            word <<= 1;
            k0 = (k0 << 1) | (k1 >> 31);
            k1 <<= 1;
        }

        input += bytes;
        length -= bits;
    }

    /* XOR the window at LENGTH and the final keystream word. */
    return tag ^ k0 ^ zuc_generate_keyword(state);
}

void zuc_eea3(uint8_t *key, uint32_t count, uint32_t bearer, uint32_t direction,
        uint32_t length, uint8_t *input, uint8_t *output)
{
    zuc_state_t state;
    uint8_t iv[16] = { 0 };
    uint32_t tail_bits = length % 8;
    size_t bytes = length / 8 + (tail_bits != 0);

    /* TS 35.221, EEA3 & EIA3 Specification, section 3.3. */
    ogs_uint64_to_buffer(count, 4, iv);
    iv[4] = (uint8_t)((bearer << 3) | ((direction & 1) << 2));
    memcpy(iv + 8, iv, 8);

    zuc_init(&state, key, iv);
    zuc_encrypt(&state, input, bytes, output);
    if (tail_bits)
        output[bytes - 1] &= (uint8_t)(0xffu << (8 - tail_bits));
}

void zuc_eia3(uint8_t *key, uint32_t count, uint32_t bearer, uint32_t direction,
        uint32_t length, uint8_t *message, uint32_t *mac)
{
    zuc_state_t state;
    uint8_t iv[16] = { 0 };
    uint8_t direction_bit = (direction & 1) << 7;

    /* TS 35.221, EEA3 & EIA3 Specification, section 4.3. */
    ogs_uint64_to_buffer(count, 4, iv);
    iv[4] = (uint8_t)(bearer << 3);
    memcpy(iv + 8, iv, 8);
    iv[8] ^= direction_bit;
    iv[14] = direction_bit;

    zuc_init(&state, key, iv);
    *mac = zuc_mac(&state, message, length);
}
